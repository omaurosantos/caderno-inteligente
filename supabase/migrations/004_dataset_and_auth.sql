create table if not exists public.dataset_sheets (
    name text primary key,
    table_name text not null,
    columns jsonb not null,
    imported_at timestamptz not null default now()
);

create table if not exists public.dataset_version (
    id smallint primary key default 1 check (id = 1),
    version bigint not null default 0,
    updated_at timestamptz not null default now()
);
insert into public.dataset_version(id, version) values (1, 0) on conflict (id) do nothing;

create table if not exists public.sheet_produtos (
    id bigint generated by default as identity primary key,
    position integer not null,
    sku text unique,
    data jsonb not null,
    active boolean not null default true,
    updated_at timestamptz,
    updated_by text
);

